#!/usr/bin/env bash
# Regenerate requirements/*.txt (pip fallback) from uv.lock.
set -euo pipefail
cd "$(dirname "$0")/.."
common=(--no-hashes --no-emit-project --no-dev -q --extra video --extra gym --extra build)
hdr="# pip fallback (uv users: see Makefile). Generated by \`make requirements\` from uv.lock."
{ echo "$hdr"; uv export "${common[@]}"; } > requirements/base.txt
{ echo "$hdr"; echo "--extra-index-url https://download.pytorch.org/whl/cpu"; uv export "${common[@]}" --extra cpu; } > requirements/cpu.txt
{ echo "$hdr"; echo "--extra-index-url https://download.pytorch.org/whl/xpu"; uv export "${common[@]}" --extra xpu; } > requirements/xpu.txt
{ echo "$hdr"; uv export --no-hashes --no-emit-project --only-dev -q; } > requirements/dev.txt
echo "wrote requirements/{base,cpu,xpu,dev}.txt"
